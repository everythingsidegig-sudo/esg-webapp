// Generates supabase/migrations/20240101000041_service_catalog_seed.sql from src/lib/service-catalog.ts.
// Run:  node scripts/gen-catalog-seed.mjs
// The catalog file is the single source of truth; a test fails if the generated seed and the catalog differ.
import { writeFile } from "node:fs/promises";
import { CATALOG } from "../src/lib/service-catalog.ts";

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const lines = [];
lines.push("-- GENERATED by scripts/gen-catalog-seed.mjs from src/lib/service-catalog.ts -- do not edit by hand.");
lines.push("-- Seeds the 23-category service catalog (migration 0040 creates the tables). Safe to run again: it only");
lines.push("-- inserts missing entries and refreshes names, order and the verification flag; it never changes `enabled`.");
lines.push("begin;", "");

lines.push("insert into public.service_categories (id, name, sort_order) values");
lines.push(CATALOG.map((c, i) => `  (${q(c.id)}, ${q(c.name)}, ${i + 1})`).join(",\n"));
lines.push("on conflict (id) do update set name = excluded.name, sort_order = excluded.sort_order;", "");

lines.push("insert into public.services (id, category_id, name, sort_order, requires_verification) values");
lines.push(CATALOG.flatMap((c) => c.services.map((s, i) => `  (${q(s.id)}, ${q(c.id)}, ${q(s.name)}, ${i + 1}, ${s.regulated})`)).join(",\n"));
lines.push("on conflict (id) do update set name = excluded.name, sort_order = excluded.sort_order, requires_verification = excluded.requires_verification;", "");

lines.push("insert into public.subservices (id, service_id, name, sort_order) values");
lines.push(CATALOG.flatMap((c) => c.services.flatMap((s) => s.subservices.map((u, i) => `  (${q(u.id)}, ${q(s.id)}, ${q(u.name)}, ${i + 1})`))).join(",\n"));
lines.push("on conflict (id) do update set name = excluded.name, sort_order = excluded.sort_order;", "");
lines.push("commit;", "");

await writeFile(new URL("../supabase/migrations/20240101000041_service_catalog_seed.sql", import.meta.url), lines.join("\n"));
console.log("wrote 20240101000041_service_catalog_seed.sql");
